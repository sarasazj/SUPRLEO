import fs from "node:fs";

const ISS_NORAD_ID = 25544;
const PNU_LAT = 24.856155;
const PNU_LON = 46.72139;
const PNU_ALT_METERS = 620;
const MIN_ELEVATION_DEGREES = 5;
const LOOKAHEAD_DAYS = Number(process.env.N2YO_LOOKAHEAD_DAYS || 10);
const OUTPUT_PATH = "n2yo-passes.js";

const apiKey = process.env.N2YO_API_KEY;

if (!apiKey) {
  throw new Error("Missing N2YO_API_KEY environment variable.");
}

const endpoint =
  `https://api.n2yo.com/rest/v1/satellite/radiopasses/${ISS_NORAD_ID}/` +
  `${PNU_LAT}/${PNU_LON}/${PNU_ALT_METERS}/` +
  `${LOOKAHEAD_DAYS}/${MIN_ELEVATION_DEGREES}/` +
  `&apiKey=${encodeURIComponent(apiKey)}`;

const response = await fetch(endpoint);
if (!response.ok) {
  throw new Error(`N2YO HTTP ${response.status}`);
}

const payload = await response.json();
if (payload.error) {
  throw new Error(`N2YO error: ${payload.error}`);
}

if (!Array.isArray(payload.passes)) {
  throw new Error("N2YO response did not include a passes array.");
}

const publicSnapshot = {
  generatedAt: new Date().toISOString(),
  observer: {
    name: "PNU Radio Telescope",
    lat: PNU_LAT,
    lon: PNU_LON,
    altMeters: PNU_ALT_METERS,
  },
  info: payload.info || {},
  passes: payload.passes,
};

const fileContents =
  "// Cached N2YO ISS radio-pass snapshot for static/offline demos. Generated by GitHub Actions.\n" +
  "window.SUPR_N2YO_PASSES_SNAPSHOT = " +
  JSON.stringify(publicSnapshot, null, 2) +
  ";\n";

fs.writeFileSync(OUTPUT_PATH, fileContents, "utf8");
console.log(`Updated ${OUTPUT_PATH} with ${payload.passes.length} ISS passes.`);
